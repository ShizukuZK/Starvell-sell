class _SafeDict(dict):
    def __missing__(self, key: str) -> str:
        return "{" + key + "}"


def render(template: str, **kwargs: Any) -> str:
    try:
        return template.format_map(_SafeDict(**kwargs))
    except Exception:
        return template


def fmt_expires(iso_or_ts: Any, tz_offset_hours: int = 3) -> str:
    """Читаемая дата окончания аренды в часовом поясе продавца."""
    ts = parse_ts(iso_or_ts)
    if not ts:
        return "—"
    dt = datetime.fromtimestamp(ts, tz=timezone.utc) + timedelta(hours=tz_offset_hours)
    sign = "+" if tz_offset_hours >= 0 else "-"
    return dt.strftime("%d.%m.%Y %H:%M") + f" (UTC{sign}{abs(tz_offset_hours)})"


def parse_ts(value: Any) -> float:
    """ISO-8601 или unix -> unix timestamp (0 при неудаче)."""
    if value in (None, ""):
        return 0.0
    if isinstance(value, (int, float)):
        return float(value)
    text = str(value).strip().replace("Z", "+00:00")
    try:
        dt = datetime.fromisoformat(text)
    except ValueError:
        return 0.0
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    return dt.timestamp()
